#!/usr/bin/env python3
"""Measure a Rust workspace, so that a reviewer knows what to read first.

Run it from inside the workspace. It prints a Markdown summary and writes that,
with the full data, to target/quality/. Standard library only. A tool that is
not installed is listed under "Skipped" and the rest still runs.
"""

import argparse
import collections
import datetime
import fnmatch
import itertools
import json
import os
import re
import shlex
import shutil
import signal
import statistics
import subprocess
import sys
import time

BASELINE = "quality-baseline.json"
TOP = 10
MAX_COMMIT_FILES = 25  # larger commits are renames and reformats, not coupling
MIN_SHARED_COMMITS = 4
MIN_DUPLICATE_LINES = 10
TRACKED_CC = 10  # functions at this complexity or more go into the baseline
RECENT_DAYS = 90  # a file first committed this recently has too little history to rank

PANICS = re.compile(r"\.unwrap\(\)|\.expect\(|\b(?:panic|unreachable)!\s*\(")
UNFINISHED = re.compile(r"\b(?:todo|unimplemented)!\s*\(")
UNSAFE = re.compile(r"\bunsafe\b")
IGNORED = re.compile(r'#\[ignore(?:\s*=\s*"([^"]*)")?\s*\]')
GENERATED = re.compile(r"@generated|generated by|auto-?generated|do not edit", re.I)
TEST_MOD = re.compile(r"^\s*(?:pub(?:\([^)]*\))?\s+)?mod\s+\w+\s*\{?\s*$")
STRING = re.compile(r'"(?:[^"\\]|\\.)*"')
WORD = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
RENAME = re.compile(r"^(.*)\{(.*) => (.*)\}(.*)$")


def run(cmd, cwd, timeout=None):
    """Returns (status, stdout, stderr), or None when the program is not installed."""
    try:
        child = subprocess.Popen(cmd, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
                                 errors="replace", start_new_session=True)
    except FileNotFoundError:
        return None
    try:
        out, err = child.communicate(timeout=timeout)
    except subprocess.TimeoutExpired:
        os.killpg(child.pid, signal.SIGKILL)  # cargo's test binaries too, not only cargo
        child.communicate()
        return (124, "", "timed out after %s s" % timeout)
    return (child.returncode, out, err)


def tail(text):
    return " | ".join(line.strip() for line in text.strip().splitlines()[-4:])


def renamed(path):
    """(old, new) for a rename line of `git log --numstat -M`, else None."""
    match = RENAME.match(path)
    if match:
        before, old, new, after = match.groups()
        return (before + old + after).replace("//", "/"), (before + new + after).replace("//", "/")
    if " => " in path:
        return tuple(path.split(" => ", 1))
    return None


def read_lcov(path, base):
    """{absolute file: {line: hits}}"""
    hits, current = collections.defaultdict(dict), None
    with open(path, errors="replace") as handle:
        for raw in handle:
            if raw.startswith("SF:"):
                current = os.path.normpath(os.path.join(base, raw[3:].strip()))
            elif raw.startswith("DA:") and current:
                line, count = raw[3:].strip().split(",")[:2]
                hits[current][int(line)] = max(hits[current].get(int(line), 0), int(float(count)))
    return hits


class Audit:
    def __init__(self, args):
        self.args = args
        self.skipped, self.notes, self.facts = [], [], {}
        self.commits, self.functions, self.lcov = [], [], None
        self.recent, self.untested = set(), []

    def skip(self, what, why):
        self.skipped.append("%s (%s)" % (what, why))

    # ---- workspace and sources

    def workspace(self):
        result = run(["cargo", "metadata", "--no-deps", "--format-version", "1"], os.getcwd())
        if result is None or result[0] != 0:
            sys.exit("cargo metadata failed here:\n%s" % (result[2].strip() if result else "cargo is not installed"))
        meta = json.loads(result[1])
        self.ws = meta["workspace_root"]
        self.target = meta["target_directory"]
        git = run(["git", "rev-parse", "--show-toplevel"], self.ws)
        self.git = bool(git and git[0] == 0)
        self.root = git[1].strip() if self.git else self.ws
        members = [p for p in meta["packages"] if p["id"] in set(meta["workspace_members"])]
        names = {p["name"] for p in members}
        self.crates = {}
        for package in members:
            folder = os.path.relpath(os.path.dirname(package["manifest_path"]), self.root)
            parts = set(folder.split(os.sep))
            deps = [d for d in package["dependencies"] if d.get("kind") != "dev"]
            self.crates[package["name"]] = {
                "dir": "" if folder == "." else folder,
                "role": "test" if parts & {"tests", "benches"} else "example" if "examples" in parts else "src",
                "uses": {d["name"] for d in deps if d.get("path") and d["name"] in names},
                "declared": sorted({((d.get("rename") or d["name"]).replace("-", "_"), d["name"]) for d in deps}),
            }
        self.out = os.path.join(self.target, "quality")
        os.makedirs(self.out, exist_ok=True)

    def crate_of(self, rel):
        owners = [(len(c["dir"]), name) for name, c in self.crates.items()
                  if c["dir"] == "" or rel.startswith(c["dir"] + "/")]
        return max(owners)[1] if owners else None

    def kind_of(self, rel, crate):
        if self.crates[crate]["role"] != "src":
            return self.crates[crate]["role"]
        parts = rel[len(self.crates[crate]["dir"]):].lstrip("/").split("/")
        stem = parts[-1][:-3]
        if {"tests", "benches"} & set(parts[:-1]) or stem in ("tests", "test") or stem.endswith(("_test", "_tests")):
            return "test"
        return "example" if "examples" in parts[:-1] else "src"

    def sources(self):
        if self.git:
            listing = ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", "*.rs"]
            listed = [p for p in run(listing, self.root)[1].split("\0") if p]
        else:
            listed = [os.path.relpath(os.path.join(folder, name), self.root)
                      for crate in self.crates.values()
                      for folder, dirs, names in os.walk(os.path.join(self.root, crate["dir"]))
                      if "/target" not in folder for name in names if name.endswith(".rs")]
        self.files, self.words, self.ignored, generated = {}, collections.defaultdict(set), [], 0
        for rel in sorted(set(listed)):
            crate = self.crate_of(rel)
            path = os.path.join(self.root, rel)
            if not crate or not os.path.isfile(path) or any(fnmatch.fnmatch(rel, g) for g in self.args.exclude):
                continue
            with open(path, errors="replace") as handle:
                lines = handle.read().splitlines()
            for line in lines:
                self.words[crate].update(WORD.findall(line))
            if any(GENERATED.search(line) for line in lines[:5] if line.lstrip().startswith("//")):
                generated += 1
                continue
            self.files[rel] = self.scan(rel, crate, lines)
        if not self.files:
            sys.exit("no Rust source files found in the workspace members")
        if generated:
            self.notes.append("%d files with a generated-code marker in their first lines are left out." % generated)

    def scan(self, rel, crate, lines):
        kind = self.kind_of(rel, crate)
        info = {"crate": crate, "kind": kind, "src_lines": 0, "test_lines": 0, "panics": 0, "unsafe": 0,
                "unfinished": 0}
        in_test = kind != "src"
        for index, line in enumerate(lines):
            text = line.strip()
            if not text or text.startswith("//"):
                continue
            ignore = IGNORED.search(text)
            if ignore:
                self.ignored.append({"file": rel, "line": index + 1, "reason": ignore.group(1)})
            if not in_test and text == "#[cfg(test)]":
                following = [l for l in lines[index + 1:index + 4] if not l.strip().startswith("#[")]
                if following and TEST_MOD.match(following[0]):
                    in_test, info["test_start"] = True, index + 1
                    continue
            if in_test:
                info["test_lines"] += kind != "example"
                continue
            info["src_lines"] += 1
            text = STRING.sub('""', text)
            info["panics"] += len(PANICS.findall(text))
            info["unsafe"] += len(UNSAFE.findall(text))
            info["unfinished"] += len(UNFINISHED.findall(text))
        return info

    # ---- git history

    def log(self, extra):
        """Commits newest first, as [hash, date, author, paths], with renamed paths mapped to today's."""
        cmd = ["git", "log", "--no-merges", "-M", "--numstat", "--date=short", "--format=@@%h%x09%ad%x09%an"]
        result = run(cmd + extra + ["--", "*.rs"], self.root)
        commits, alias = [], {}
        for line in result[1].splitlines() if result and result[0] == 0 else []:
            if line.startswith("@@"):
                commits.append(line[2:].split("\t", 2) + [[]])
            elif line.strip() and commits:
                path = line.split("\t", 2)[2]
                names = renamed(path)
                if names:
                    alias[names[0]] = alias.get(names[1], names[1])
                path = alias.get(names[0] if names else path, path)
                if path in self.files:
                    commits[-1][3].append(path)
        return [c for c in commits if c[3]]

    def history(self):
        if not self.git:
            return self.skip("churn and coupling", "not a git repository")
        everything = self.log([])
        self.commits = self.log(["--since", self.args.since]) or everything
        if not everything:
            return self.skip("churn and coupling", "no commits touch Rust files")
        for info in self.files.values():
            info["commits"] = 0
        for _, _, _, paths in self.commits:
            for path in set(paths):
                self.files[path]["commits"] += 1
        for _, date, _, paths in everything:  # newest first, so the last write is the first commit
            for path in paths:
                self.files[path]["first_commit"] = date
        day = datetime.date.fromisoformat
        first, last = self.commits[-1][1], self.commits[0][1]
        self.facts["history"] = {"commits": len(self.commits), "authors": len({c[2] for c in self.commits}),
                                 "first": first, "last": last}
        if len(self.commits) < 20 or (day(last) - day(first)).days < RECENT_DAYS:
            self.notes.append("The history is short (%d commits, %s to %s), so the hotspot ranking mostly "
                              "follows file size." % (len(self.commits), first, last))
            return
        cutoff = (day(everything[0][1]) - datetime.timedelta(days=RECENT_DAYS)).isoformat()
        source = {rel: f for rel, f in self.files.items() if f["kind"] == "src"}
        recent = {rel for rel, f in source.items() if f.get("first_commit", "") >= cutoff}
        share = sum(source[rel]["src_lines"] for rel in recent) / max(1, sum(f["src_lines"] for f in source.values()))
        if share >= 0.2:
            self.recent = recent
            self.notes.append("%d%% of the source is in files first committed in the last %d days of history. "
                              "Code split out of an older file starts with no history, so the hotspot ranking "
                              "understates it; the most complex of these files are listed under the table."
                              % (round(100 * share), RECENT_DAYS))

    def coupling(self):
        """Pairs of files in different crates that keep changing in the same small commits."""
        pairs = collections.defaultdict(list)
        for commit, _, _, paths in self.commits:
            source = sorted({p for p in paths if self.files[p]["kind"] == "src"})
            if len(set(paths)) <= MAX_COMMIT_FILES:
                for pair in itertools.combinations(source, 2):
                    if self.files[pair[0]]["crate"] != self.files[pair[1]]["crate"]:
                        pairs[pair].append((commit, len(set(paths))))
        found = []
        for (first, second), shared in pairs.items():
            average = (self.files[first]["commits"] + self.files[second]["commits"]) / 2
            if len(shared) >= MIN_SHARED_COMMITS and len(shared) / average >= 0.4:
                found.append({"first": first, "second": second, "shared": len(shared),
                              "files_per_commit": int(statistics.median(size for _, size in shared)),
                              "commits": [commit for commit, _ in shared]})
        self.facts["coupling"] = sorted(found, key=lambda p: -p["shared"])

    # ---- coverage, complexity, duplicates, clippy

    def coverage(self):
        if self.args.lcov:
            self.lcov = os.path.abspath(self.args.lcov)
            self.facts["coverage_from"] = "the LCOV file `%s`" % self.args.lcov
        elif self.args.tier != "full":
            return self.skip("coverage", "quick tier")
        elif not shutil.which("cargo-llvm-cov"):
            return self.skip("coverage", "cargo-llvm-cov is not installed")
        else:
            debug = os.path.join(self.target, "debug")
            if os.path.isdir(debug) and not os.path.isdir(os.path.join(self.target, "llvm-cov-target")):
                size = run(["du", "-sk", debug], self.ws, 120)
                need = int(size[1].split()[0]) * 1024 if size and size[0] == 0 else 0
                free = shutil.disk_usage(self.target).free
                if free < need + 5 * 2 ** 30:
                    return self.skip("coverage", "the instrumented build needs about %.0f GB and %.0f GB is free; "
                                     "free some space or pass --lcov" % (need / 2 ** 30, free / 2 ** 30))
            lcov = os.path.join(self.out, "lcov.info")
            cmd = ["cargo", "llvm-cov", "--workspace", "--lcov", "--output-path", lcov]
            sys.stderr.write("collect: running the tests under cargo llvm-cov\n")
            started = time.time()
            result = run(cmd + shlex.split(self.args.llvm_cov_args), self.ws, self.args.timeout)
            if result[0] != 0:
                return self.skip("coverage", "cargo llvm-cov failed: " + tail(result[2]))
            self.lcov = lcov
            self.facts["coverage_from"] = "`%s`, %d s, tests passed" % (
                " ".join(["cargo llvm-cov --workspace"] + shlex.split(self.args.llvm_cov_args)),
                time.time() - started)
        for path, hits in read_lcov(self.lcov, self.ws).items():
            info = self.files.get(os.path.relpath(path, self.root))
            if info and info["kind"] == "src":
                info["covered"] = [sum(1 for h in hits.values() if h), len(hits)]

    def complexity(self):
        if not shutil.which("cargo-crap"):
            return self.skip("complexity and duplicates", "cargo-crap is not installed")
        report = os.path.join(self.out, "crap.json")
        cmd = ["cargo", "crap", "--workspace", "--format", "json", "--duplicates", "--output", report]
        result = run(cmd + (["--lcov", self.lcov] if self.lcov else []), self.ws, self.args.timeout)
        if result[0] != 0:
            return self.skip("complexity and duplicates", "cargo crap failed: " + tail(result[2]))
        with open(report) as handle:
            data = json.load(handle)
        for entry in data["entries"]:
            rel = os.path.relpath(entry["file"], self.root)
            info = self.files.get(rel)
            if not info or info["kind"] != "src":
                continue
            function = {"file": rel, "line": entry["line"], "function": entry["function"], "crate": info["crate"],
                        "cc": int(entry["cyclomatic"]), "coverage": entry["coverage"] if self.lcov else None,
                        "crap": round(entry["crap"], 1) if self.lcov else None}
            self.functions.append(function)
            info["cc_sum"] = info.get("cc_sum", 0) + function["cc"]
            if function["cc"] > info.get("worst", (0,))[0]:
                info["worst"] = (function["cc"], function["function"])
        self.functions.sort(key=lambda f: (-(f["crap"] or 0), -f["cc"]))
        self.duplicates(data.get("duplicates", []))

    def duplicates(self, pairs):
        """Join cargo-crap's pairs of similar functions into groups, largest first."""
        parent, member = {}, {}

        def find(key):
            while parent[key] != key:
                key = parent[key]
            return key

        for pair in pairs:
            sides = []
            for side in ("first", "second"):
                rel = os.path.relpath(pair[side + "_file"], self.root)
                start = pair[side + "_start_line"]
                sides.append({"file": rel, "line": start, "function": pair[side + "_function"],
                              "lines": pair[side + "_end_line"] - start + 1})
            if any(self.files.get(s["file"], {}).get("kind") != "src" or s["lines"] < MIN_DUPLICATE_LINES
                   for s in sides):
                continue
            for side in sides:
                key = (side["file"], side["line"])
                parent.setdefault(key, key)
                member[key] = side
            parent[find((sides[0]["file"], sides[0]["line"]))] = find((sides[1]["file"], sides[1]["line"]))
        groups = collections.defaultdict(list)
        for key in sorted(parent):
            groups[find(key)].append(member[key])
        self.facts["duplicates"] = sorted(groups.values(), key=lambda g: -sum(f["lines"] for f in g))

    def clippy(self):
        """Cognitive complexity sees inside macro calls such as select!, which cyclomatic complexity does not."""
        if self.args.tier != "full":
            return self.skip("cognitive complexity", "quick tier")
        sys.stderr.write("collect: running cargo clippy\n")
        result = run(["cargo", "clippy", "--workspace", "--message-format=json", "--", "-W",
                      "clippy::cognitive_complexity"], self.ws, self.args.timeout)
        if result is None or (result[0] != 0 and "{" not in result[1]):
            return self.skip("cognitive complexity", "cargo clippy failed")
        starts = collections.defaultdict(list)
        for function in sorted(self.functions, key=lambda f: f["line"]):
            starts[function["file"]].append(function)
        for raw in result[1].splitlines():
            message = (json.loads(raw).get("message") or {}) if raw.startswith("{") else {}
            if (message.get("code") or {}).get("code") != "clippy::cognitive_complexity":
                continue
            span = next(s for s in message["spans"] if s["is_primary"])
            rel = os.path.relpath(os.path.join(self.ws, span["file_name"]), self.root)
            score = re.search(r"\((\d+)/(\d+)\)", message["message"])
            owner = [f for f in starts.get(rel, []) if f["line"] <= span["line_start"]]
            if owner and score and span["line_start"] < self.files[rel].get("test_start", 10 ** 9):
                owner[-1]["cognitive"] = int(score.group(1))
                self.facts["cognitive_limit"] = int(score.group(2))

    # ---- dependencies

    def dependencies(self):
        unused = {}
        for name, crate in sorted(self.crates.items()):
            if crate["role"] == "src" and self.words.get(name):
                missing = sorted({dep for ident, dep in crate["declared"] if ident not in self.words[name]})
                if missing:
                    unused[name] = missing
        self.facts["unused_candidates"] = unused
        if not os.path.isfile(os.path.join(self.ws, "Cargo.lock")):
            return self.skip("advisories", "no Cargo.lock")
        result = run(["cargo", "audit", "--json"], self.ws, 300)
        try:
            report = json.loads(result[1])
        except (TypeError, ValueError):
            return self.skip("advisories", "cargo-audit is not installed or failed")
        found = collections.defaultdict(list)
        entries = [("vulnerability", item) for item in report["vulnerabilities"]["list"]]
        entries += [(kind, item) for kind, items in report.get("warnings", {}).items() for item in items]
        for kind, item in entries:
            advisory = item.get("advisory") or {}
            patched = (item.get("versions") or {}).get("patched") or []
            key = "%s `%s` %s" % (kind, item["package"]["name"], item["package"]["version"])
            found[key].append({"id": advisory.get("id"), "title": advisory.get("title"),
                               "fix": patched[0].split(",")[0].lstrip(">=^ ") if patched else None})
        self.facts["advisories"] = found

    # ---- ranking

    def rank(self):
        files = self.files
        source = [f for f in files.values() if f["kind"] == "src"]
        totals = {"files": len(files), "crates": len(self.crates),
                  "src_lines": sum(f["src_lines"] for f in files.values()),
                  "test_lines": sum(f["test_lines"] for f in files.values()),
                  "panics": sum(f["panics"] for f in source), "unsafe": sum(f["unsafe"] for f in source),
                  "unfinished": sum(f["unfinished"] for f in source), "ignored_tests": len(self.ignored),
                  "vulnerabilities": sum(len(v) for k, v in self.facts.get("advisories", {}).items()
                                         if k.startswith("vulnerability")),
                  "unused_dependency_candidates": sum(len(v) for v in self.facts["unused_candidates"].values())}
        crates = {}
        for name, crate in self.crates.items():
            own = [f for f in files.values() if f["crate"] == name]
            hit = sum(f["covered"][0] for f in own if "covered" in f)
            found = sum(f["covered"][1] for f in own if "covered" in f)
            crates[name] = {"src_lines": sum(f["src_lines"] for f in own),
                            "test_lines": sum(f["test_lines"] for f in own),
                            "commits": sum(1 for c in self.commits if any(files[p]["crate"] == name for p in c[3])),
                            "coverage": round(100 * hit / found, 1) if found else None,
                            "used_by": sum(1 for other in self.crates.values() if name in other["uses"])}
            if self.lcov and crates[name]["src_lines"] and not hit:
                self.untested.append(name)
        if self.lcov:
            def percent(rows):
                found = sum(f["covered"][1] for f in rows if "covered" in f)
                return round(100 * sum(f["covered"][0] for f in rows if "covered" in f) / found, 1) if found else 0.0
            totals["coverage"] = percent(source)
            totals["coverage_tested_crates"] = percent([f for f in source if f["crate"] not in self.untested])
        if self.functions:
            values = sorted(f["cc"] for f in self.functions)
            totals.update(functions=len(values), cc_median=int(statistics.median(values)),
                          cc_p90=values[int(0.9 * (len(values) - 1))], cc_max=values[-1],
                          duplicate_groups=len(self.facts["duplicates"]))
            if self.lcov:
                totals["crap_over_30"] = sum(1 for f in self.functions if f["crap"] > 30)
        hotspots = []
        for rel, info in files.items():
            weight = info.get("cc_sum", 0) if self.functions else info["src_lines"]
            if info["kind"] == "src" and info.get("commits") and weight:
                hotspots.append({"file": rel, "score": info["commits"] * weight, "weight": weight,
                                 "commits": info["commits"], "first_commit": info.get("first_commit"),
                                 "worst": info.get("worst"),
                                 "coverage": round(100 * info["covered"][0] / info["covered"][1])
                                 if info.get("covered", [0, 0])[1] else None})
        hotspots.sort(key=lambda h: -h["score"])
        hot = {h["file"] for h in hotspots[:TOP]}
        for function in self.functions:
            function["hot"] = function["file"] in hot
        self.facts.update(totals=totals, crates=crates, hotspots=hotspots[:50], functions=self.functions,
                          recent_files=sorted((h for h in hotspots if h["file"] in self.recent),
                                              key=lambda h: -h["weight"])[:5],
                          untested_crates=self.untested, ignored_tests=self.ignored, files=files,
                          has_coverage=bool(self.lcov), lcov=self.lcov, skipped=self.skipped, notes=self.notes)

    # ---- baseline and lookups

    def tracked(self, functions):
        return {"%s::%s" % (f["file"], f["function"]): {"cc": f["cc"], "crap": f["crap"]}
                for f in sorted(functions, key=lambda f: f["cc"]) if f["cc"] >= TRACKED_CC}

    def baseline_path(self):
        return os.path.abspath(self.args.baseline or os.path.join(self.ws, BASELINE))

    def compare(self):
        if not os.path.isfile(self.baseline_path()):
            return
        with open(self.baseline_path()) as handle:
            base = json.load(handle)
        totals = self.facts["totals"]
        metric = "crap" if self.lcov and base.get("has_coverage") else "cc"
        now, before = self.tracked(self.functions), base["functions"]
        changes = {"new": [(k, None, v[metric]) for k, v in now.items() if k not in before],
                   "worse": [(k, before[k][metric], v[metric]) for k, v in now.items()
                             if k in before and v[metric] > before[k][metric] + 0.05],
                   "better": [(k, before[k][metric], v[metric]) for k, v in now.items()
                              if k in before and v[metric] < before[k][metric] - 0.05],
                   "gone": [(k, v[metric], None) for k, v in before.items() if k not in now]}
        self.facts["baseline"] = {
            "date": base["date"], "commit": base["commit"], "metric": metric, "functions": changes,
            "totals": {k: [base["totals"][k], v] for k, v in totals.items()
                       if k in base["totals"] and base["totals"][k] != v}}

    def last_run(self):
        path = os.path.join(self.out, "facts.json")
        if not os.path.isfile(path):
            sys.exit("no earlier run in %s. Run the collector first." % self.out)
        with open(path) as handle:
            return json.load(handle)

    def save_baseline(self):
        facts = self.last_run()
        base = {"date": facts["date"], "commit": facts["commit"], "has_coverage": facts["has_coverage"],
                "totals": facts["totals"], "functions": self.tracked(facts["functions"])}
        with open(self.baseline_path(), "w") as handle:
            json.dump(base, handle, indent=1, sort_keys=True)
        print("Baseline written to %s from the run of %s at commit %s, %s coverage."
              % (self.baseline_path(), base["date"], base["commit"], "with" if base["has_coverage"] else "without"))

    def uncovered(self):
        path, _, span = self.args.uncovered.partition(":")
        lcov = os.path.abspath(self.args.lcov) if self.args.lcov else self.last_run().get("lcov")
        if not lcov or not os.path.isfile(lcov):
            sys.exit("no coverage data. Run with --tier full first, or pass --lcov FILE.")
        data = read_lcov(lcov, self.ws)
        hits = next((data[p] for p in (os.path.normpath(os.path.join(base, path))
                                       for base in (os.getcwd(), self.root, self.ws)) if p in data), None)
        if hits is None:
            sys.exit("`%s` is not in the coverage data: not compiled for the tests, or a wrong path." % path)
        low, _, high = span.partition("-")
        low, high = int(low or 1), int(high or max(hits))
        measured = sorted(line for line in hits if low <= line <= high)
        ranges, start, previous = [], None, None
        for line in measured + [None]:
            if line is None or hits[line]:
                if start is not None:
                    ranges.append(str(start) if start == previous else "%d-%d" % (start, previous))
                start = None
            elif start is None:
                start = line
            previous = line
        missed = sum(1 for line in measured if not hits[line])
        print("`%s`, lines %d-%d: %d of %d instrumented lines never ran%s"
              % (path, low, high, missed, len(measured), ": " + ", ".join(ranges) + "." if ranges else "."))

    # ---- output

    def summary(self):
        facts, totals, out = self.facts, self.facts["totals"], []

        def table(header, rows):
            out.append("| " + " | ".join(header) + " |")
            out.append("|" + " --- |" * len(header))
            out.extend("| " + " | ".join("-" if cell is None else str(cell) for cell in row) + " |" for row in rows)
            out.append("")

        def section(title):
            out.extend(["## " + title, ""])

        def place(function):
            return "`%s:%d`" % (function["file"], function["line"])

        out.append("# Quality facts: %s" % os.path.basename(self.root))
        out.append("")
        history = facts.get("history")
        out.append("%s, commit %s, %s tier.%s" % (
            facts["date"], facts["commit"], self.args.tier,
            " History: %d commits by %d author%s, %s to %s." % (
                history["commits"], history["authors"], "" if history["authors"] == 1 else "s",
                history["first"], history["last"])
            if history else ""))
        if facts.get("coverage_from"):
            out.append("Coverage is from %s." % facts["coverage_from"])
        out.append("Skipped: %s." % ("; ".join(self.skipped) or "nothing"))
        out.append("")
        if self.notes:
            out.extend(["> " + note for note in self.notes] + [""])

        section("Totals")
        out.append("- %d source lines and %d test lines, in %d files and %d crates."
                   % (totals["src_lines"], totals["test_lines"], totals["files"], totals["crates"]))
        if self.functions:
            out.append("- %d functions. Cyclomatic complexity: median %d, 90th percentile %d, max %d."
                       % (totals["functions"], totals["cc_median"], totals["cc_p90"], totals["cc_max"]))
        if self.lcov:
            rest = " (%.1f%% without the %d crates that no test runs)" % (
                totals["coverage_tested_crates"], len(self.untested)) if self.untested else ""
            out.append("- Line coverage %.1f%%%s. %d functions are above CRAP 30."
                       % (totals["coverage"], rest, totals["crap_over_30"]))
        out.append("- Outside tests: %d `unwrap`/`expect`/`panic!`, %d `unsafe`, %d `todo!`. %d tests are ignored."
                   % (totals["panics"], totals["unsafe"], totals["unfinished"], totals["ignored_tests"]))
        out.append("")

        base = facts.get("baseline")
        if base:
            section("Since the baseline of %s (commit %s)" % (base["date"], base["commit"]))
            out.extend("- %s: %s, was %s" % (key, now, before) for key, (before, now) in sorted(base["totals"].items()))
            for label, group in base["functions"].items():
                if group:
                    group.sort(key=lambda c: -(c[2] or c[1]))
                    out.append("- %d functions %s on %s: %s" % (len(group), label, base["metric"].upper(), ", ".join(
                        "`%s` (%s)" % (name, " to ".join(str(v) for v in (before, now) if v is not None))
                        for name, before, now in group[:TOP])))
            if not base["totals"] and not any(base["functions"].values()):
                out.append("Nothing changed.")
            out.append("")

        section("Crates")
        rows = sorted(facts["crates"].items(), key=lambda item: -item[1]["src_lines"])[:8]
        table(["Crate", "Source lines", "Test lines", "Commits", "Coverage %", "Used by"],
              [(name, c["src_lines"], c["test_lines"], c["commits"], c["coverage"], c["used_by"]) for name, c in rows])

        if facts["hotspots"]:
            section("Hotspot files")
            unit = "summed complexity" if self.functions else "source lines"
            out.extend(["Ranked by commits times %s." % unit, ""])
            table(["File", "Commits", "First commit", unit.capitalize(), "Worst function (CC)", "Coverage %"],
                  [("`%s`" % h["file"], h["commits"], h["first_commit"], h["weight"],
                    "`%s` (%d)" % (h["worst"][1], h["worst"][0]) if h["worst"] else None, h["coverage"])
                   for h in facts["hotspots"][:TOP]])
            if facts["recent_files"]:
                out.extend(["Recently created, so understated above: " + ", ".join(
                    "`%s` (%d, since %s)" % (h["file"], h["weight"], h["first_commit"])
                    for h in facts["recent_files"]) + ".", ""])

        if self.functions:
            section("Riskiest functions")
            ranked = [f for f in self.functions if f["crate"] not in self.untested]
            out.extend(["Ranked by %s. `*` marks a function in a hotspot file above."
                        % ("CRAP: complexity squared times the uncovered share cubed, plus complexity"
                           if self.lcov else "cyclomatic complexity; there is no coverage in this run"), ""])
            columns = [("Function", lambda f: "`%s`%s" % (f["function"], " *" if f["hot"] else "")),
                       ("Location", place), ("CC", lambda f: f["cc"])]
            if "cognitive_limit" in facts:
                columns.append(("Cognitive", lambda f: f.get("cognitive")))
            if self.lcov:
                columns.append(("Coverage %", lambda f: "none" if f["coverage"] is None else round(f["coverage"])))
                columns.append(("CRAP", lambda f: f["crap"]))
            table([name for name, _ in columns], [[cell(f) for _, cell in columns] for f in ranked[:15]])
            rest = ranked[15:]
            covered = sorted((f for f in rest if f["cc"] >= 20), key=lambda f: -f["cc"])[:TOP] if self.lcov else []
            if covered:
                out.extend(["Complex but covered, so not in the table: " + ", ".join(
                    "`%s`%s %s (CC %d)" % (f["function"], " *" if f["hot"] else "", place(f), f["cc"])
                    for f in covered) + ".", ""])
            nested = sorted((f for f in rest if f.get("cognitive")), key=lambda f: -f["cognitive"])[:TOP]
            if nested:
                out.extend(["Over clippy's cognitive-complexity limit of %d, and not in the table: "
                            % facts["cognitive_limit"] + ", ".join(
                                "`%s` %s (%d)" % (f["function"], place(f), f["cognitive"]) for f in nested) + ".", ""])
            if self.untested:
                out.extend(["Not ranked, because no test runs these crates at all: %s."
                            % ", ".join("`%s`" % name for name in self.untested), ""])

        if facts.get("coupling"):
            section("Files in different crates that change together")
            table(["File", "Changes with", "Shared commits", "Files per shared commit"],
                  [("`%s`" % p["first"], "`%s`" % p["second"], p["shared"], p["files_per_commit"])
                   for p in facts["coupling"][:5]])

        if facts.get("duplicates"):
            section("Near-duplicate functions")
            for group in facts["duplicates"][:5]:
                names = sorted({f["function"] for f in group})
                sizes = sorted({min(f["lines"] for f in group), max(f["lines"] for f in group)})
                out.append("- %s, %d copies of %s lines: %s" % (
                    " / ".join("`%s`" % n for n in names[:3]), len(group), " to ".join(map(str, sizes)),
                    ", ".join(place(f) for f in group[:4])))
            out.append("")

        section("Tests and panics")
        if self.ignored:
            where = collections.Counter(i["file"] for i in self.ignored).most_common(5)
            reasons = [r for r, _ in collections.Counter(i["reason"] for i in self.ignored if i["reason"]).most_common(3)]
            out.append("- %d ignored tests, most in %s.%s" % (
                len(self.ignored), ", ".join("`%s` (%d)" % pair for pair in where),
                " Reasons include: %s." % "; ".join('"%s"' % r[:70] for r in reasons) if reasons else ""))
        panicky = sorted(((f["panics"], rel) for rel, f in self.files.items() if f["kind"] == "src"), reverse=True)[:5]
        out.append("- Most `unwrap`/`expect`/`panic!` outside tests: "
                   + ", ".join("`%s` (%d)" % (rel, count) for count, rel in panicky if count) + ".")
        out.append("")

        if facts.get("advisories") or facts["unused_candidates"]:
            section("Dependencies")
            for key, items in facts.get("advisories", {}).items():
                out.append("- %s: %s" % (key, ", ".join(
                    "%s (%s)" % (i["id"], "fixed in " + i["fix"] if i["fix"] else "no fix") for i in items)))
            if facts["unused_candidates"]:
                out.append("- Declared but never named in the crate's Rust files, so possibly unused: "
                           + "; ".join("`%s`: %s" % (crate, ", ".join(deps))
                                       for crate, deps in list(facts["unused_candidates"].items())[:TOP]) + ".")
            out.append("")
        out.append("Full data: `%s`." % os.path.relpath(os.path.join(self.out, "facts.json"), self.root))
        return "\n".join(out) + "\n"

    def main(self):
        self.workspace()
        if self.args.save_baseline:
            return self.save_baseline()
        if self.args.uncovered:
            return self.uncovered()
        head = run(["git", "rev-parse", "--short", "HEAD"], self.root) if self.git else None
        self.facts.update(date=datetime.date.today().isoformat(), tier=self.args.tier,
                          commit=head[1].strip() if head and head[0] == 0 else "none")
        self.sources()
        self.history()
        self.coupling()
        self.coverage()
        self.complexity()
        self.clippy()
        self.dependencies()
        self.rank()
        self.compare()
        text = self.summary()
        with open(os.path.join(self.out, "facts.json"), "w") as handle:
            json.dump(self.facts, handle, indent=1, default=sorted)
        with open(os.path.join(self.out, "summary.md"), "w") as handle:
            handle.write(text)
        sys.stdout.write(text)


